const fs = require('fs');
const path = require('path');

let cdnBaseUrl = process.env.CDN_BASE_URL || '';

if (!cdnBaseUrl) {
  const envPath = path.resolve(__dirname, '../.env');
  if (fs.existsSync(envPath)) {
    const envContent = fs.readFileSync(envPath, 'utf8');
    const match = envContent.match(/CDN_BASE_URL\s*=\s*['"]?([^'"\r\n]+)['"]?/);
    if (match) {
      cdnBaseUrl = match[1].trim();
    }
  }
}

const targetDir = path.resolve(__dirname, '../src/environments');
if (!fs.existsSync(targetDir)) {
  fs.mkdirSync(targetDir, { recursive: true });
}

const prodEnvPath = path.join(targetDir, 'environment.ts');
const devEnvPath = path.join(targetDir, 'environment.development.ts');

const prodContent = `// Auto-generated by scripts/set-env.js
export const environment = {
  production: true,
  cdnBaseUrl: '${cdnBaseUrl}',
};
`;

const devContent = `// Auto-generated by scripts/set-env.js
export const environment = {
  production: false,
  cdnBaseUrl: '${cdnBaseUrl}',
};
`;

fs.writeFileSync(prodEnvPath, prodContent, 'utf8');
fs.writeFileSync(devEnvPath, devContent, 'utf8');

console.log(`[set-env] Injected CDN_BASE_URL: ${cdnBaseUrl ? '(configured)' : '(empty)'}`);

